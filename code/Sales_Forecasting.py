df["Marketing_Spend"] = df["Marketing_Spend"].fillna(df["Marketing_Spend"].median())

df["Revenue"] = (
    df["Units_Sold"] *
    df["Unit_Price"] *
    (1 - df["Discount_%"] / 100)
)

df.isnull().sum()

df.to_excel("cleaned_sales_data.xlsx", index=False)

