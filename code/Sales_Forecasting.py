import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_excel('/content/messy_sales_dataset.xlsx')

df.isnull().sum()

df.duplicated().sum()

df["Date"] = pd.to_datetime(
    df["Date"],
    format="mixed",
    dayfirst=True,
    errors="coerce"
)

df["Date"].isnull().sum()

df = df.drop_duplicates().copy()

df.duplicated().sum()

df.isnull().sum()

df["Region"] = df["Region"].str.strip().str.title()

